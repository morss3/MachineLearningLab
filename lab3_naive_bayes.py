import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.naive_bayes import GaussianNB
from sklearn.metrics import mean_absolute_error, mean_squared_error, accuracy_score

# ============================================================
# 5. Загрузка данных и первые 10 наблюдений
# ============================================================
FILE_NAME = "bank.csv"

df = pd.read_csv(FILE_NAME, sep=";")

print("=" * 70)
print("ЗАДАНИЕ 5. ПЕРВЫЕ 10 НАБЛЮДЕНИЙ")
print("=" * 70)
print(df.head(10).to_string())
print("\nРазмер набора данных:", df.shape)
print("\nНазвания столбцов:")
print(df.columns.tolist())

# ============================================================
# 6. Проверка пропущенных значений и выбросов
# ============================================================
print("\n" + "=" * 70)
print("ЗАДАНИЕ 6. ПРОПУЩЕННЫЕ ЗНАЧЕНИЯ И ВЫБРОСЫ")
print("=" * 70)

print("\nКоличество пропущенных значений по столбцам:")
print(df.isnull().sum())

missing_total = int(df.isnull().sum().sum())
print("\nВсего пропущенных значений:", missing_total)

# Для данной работы используются duration и pdays.
# pdays = -1 — это специальный код UCI: предыдущего контакта не было.
# Поэтому -1 не удаляется как статистический выброс.
#
# Для duration очень большие значения означают длительные телефонные
# разговоры и не являются автоматически ошибочными измерениями.
# Поэтому реальные наблюдения не удаляем без доказательства ошибки.
#
# Ниже дополнительно выводим IQR-проверку, чтобы зафиксировать наличие
# статистически крайних наблюдений.
for col in ["duration", "pdays"]:
    q1 = df[col].quantile(0.25)
    q3 = df[col].quantile(0.75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    count = int(((df[col] < lower) | (df[col] > upper)).sum())

    print(f"\n{col}:")
    print(f"Q1 = {q1:.3f}, Q3 = {q3:.3f}, IQR = {iqr:.3f}")
    print(f"Границы IQR: [{lower:.3f}; {upper:.3f}]")
    print(f"Количество статистически крайних наблюдений: {count}")

print("\nВывод по очистке:")
print("Пропущенных значений нет, поэтому удаление/заполнение пропусков не требуется.")
print("Код pdays = -1 является смысловым значением 'предыдущего контакта не было',")
print("поэтому такие наблюдения не удаляются. Большие duration также не считаются")
print("ошибками ввода без дополнительного подтверждения.")

# ============================================================
# 7. Матрица корреляции и выбор отклика/факторов
# ============================================================
print("\n" + "=" * 70)
print("ЗАДАНИЕ 7. МАТРИЦА КОРРЕЛЯЦИИ")
print("=" * 70)

# Преобразуем целевую переменную:
# no = 0, yes = 1
df["y_num"] = df["y"].map({"no": 0, "yes": 1})

numeric_cols = df.select_dtypes(include=np.number).columns
corr = df[numeric_cols].corr()

pd.set_option("display.max_columns", None)
pd.set_option("display.width", 180)

print(corr.round(3).to_string())
# Для модели берем два числовых фактора, использовавшихся
# в предыдущей лабораторной:
# X1 = duration
# X2 = pdays
# Отклик Y = y
#
# GaussianNB работает с числовыми признаками. Выбор duration и pdays
# позволяет использовать тот же набор данных и сопоставить результаты
# разных методов классификации.
features = ["duration", "pdays"]
target = "y_num"

X = df[features]
y = df[target]

print("\nПеременная отклика Y: y (no=0, yes=1)")
print("Факторы:")
print("X1 = duration — длительность последнего контакта, сек.")
print("X2 = pdays — число дней после предыдущего контакта; -1 означает,")
print("     что предыдущего контакта не было.")

# ============================================================
# 8. Обучающая и тестовая выборки
# ============================================================
print("\n" + "=" * 70)
print("ЗАДАНИЕ 8. TRAIN / TEST")
print("=" * 70)

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.25,
    random_state=9,
    stratify=y
)

print("Размер обучающей выборки X:", X_train.shape)
print("Размер обучающей выборки y:", y_train.shape)
print("Размер тестовой выборки X:", X_test.shape)
print("Размер тестовой выборки y:", y_test.shape)

# ============================================================
# 9. Визуализация данных (m = 2)
# ============================================================
print("\n" + "=" * 70)
print("ЗАДАНИЕ 9. ОБЛАКО ТОЧЕК")
print("=" * 70)

plt.figure(figsize=(9, 6))

for cls, label in [(0, "no"), (1, "yes")]:
    part = df[df["y_num"] == cls]
    plt.scatter(
        part["duration"],
        part["pdays"],
        alpha=0.35,
        s=18,
        label=label
    )

# plt.yticks([-1, 100, 200, 300, 400, 500, 600, 700, 800])
plt.xlabel("duration, сек.")
plt.ylabel("pdays, дни")
plt.title("Bank Marketing: облако точек")
plt.legend()
plt.grid(alpha=0.25)
plt.tight_layout()
plt.savefig("visual.png", dpi=200)
plt.show()


# ============================================================
# 10. Отделение прогнозного значения Y
# ============================================================
print("\n" + "=" * 70)
print("ЗАДАНИЕ 10. ОТДЕЛЕНИЕ ПЕРЕМЕННОЙ ОТКЛИКА")
print("=" * 70)

# X уже содержит только факторы, y содержит прогнозируемый класс.
print("X содержит столбцы:", X.columns.tolist())
print("y содержит переменную:", target)
print("\nПервые 5 строк X:")
print(X.head().to_string())
print("\nПервые 5 значений y:")
print(y.head().to_string())

# ============================================================
# 11. Построение натренированной модели NBK
# ============================================================
print("\n" + "=" * 70)
print("ЗАДАНИЕ 11. ГАУССОВСКИЙ НАИВНЫЙ БАЙЕСОВСКИЙ КЛАССИФИКАТОР")
print("=" * 70)

# GaussianNB — гауссовский наивный байесовский классификатор.
model = GaussianNB()

model.fit(X_train, y_train)

y_pred = model.predict(X_test)
y_prob = model.predict_proba(X_test)[:, 1]

print("Модель обучена:")
print(model)

print("\nАприорные вероятности классов:")
for cls, prob in zip(model.classes_, model.class_prior_):
    print(f"Класс {cls}: {prob:.6f}")

print("\nСредние значения признаков по классам (theta_):")
theta = pd.DataFrame(
    model.theta_,
    index=[f"class_{c}" for c in model.classes_],
    columns=features
)
print(theta.round(4).to_string())

print("\nВывод:")
print("GaussianNB оценивает распределение числовых признаков отдельно для")
print("каждого класса и затем вычисляет вероятность принадлежности объекта")
print("к каждому классу.")

# ============================================================
# 12. MAE, MSE и качество модели
# ============================================================
print("\n" + "=" * 70)
print("ЗАДАНИЕ 12. ОЦЕНКА КАЧЕСТВА")
print("=" * 70)

mae = mean_absolute_error(y_test, y_pred)
mse = mean_squared_error(y_test, y_pred)
accuracy = accuracy_score(y_test, y_pred)

print(f"MAE = {mae:.6f}")
print(f"MSE = {mse:.6f}")
print(f"Accuracy = {accuracy:.6f} ({accuracy * 100:.2f}%)")

print("\nПримечание:")
print("Для бинарных прогнозов 0/1 MAE и MSE совпадают, поскольку")
print("ошибка каждого объекта равна либо 0, либо 1.")

# ============================================================
# 13. Сравнение теоретических и эмпирических значений
# ============================================================
print("\n" + "=" * 70)
print("ЗАДАНИЕ 13. СРАВНЕНИЕ ДВУХ ТЕСТОВЫХ НАБЛЮДЕНИЙ")
print("=" * 70)

# Берем два первых объекта тестовой выборки.
comparison = X_test.iloc[:2].copy()
comparison["Фактический y"] = y_test.iloc[:2].values
comparison["Прогноз y"] = y_pred[:2]
comparison["P(no)"] = model.predict_proba(X_test.iloc[:2])[:, 0]
comparison["P(yes)"] = model.predict_proba(X_test.iloc[:2])[:, 1]

print(comparison.to_string())

print("\nВывод:")
print("Теоретическим значением здесь считаем прогноз модели,")
print("а эмпирическим — фактическое значение y из тестовой выборки.")
print("Если прогноз совпал с фактическим классом, объект классифицирован верно.")
print("Если классы различаются, для данного объекта модель допустила ошибку.")

